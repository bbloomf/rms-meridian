// Offline content pipeline: asks Claude to write one character's dialogue
// templates, validates them, asks for fixes, and writes content/dialogue/<id>.json.
// Nothing here runs at play time.
//
//   node src/dialogue/pipeline.ts marble egg          generate (skips existing files)
//   node src/dialogue/pipeline.ts marble --force      regenerate, overwriting
//   node src/dialogue/pipeline.ts marble --dry-run    print the prompt, call nothing
//
// Credentials: ANTHROPIC_API_KEY, or an `ant auth login` profile.

import Anthropic from "@anthropic-ai/sdk";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CAST, CHAR_IDS } from "../data.ts";
import type { CharId } from "../data.ts";
import { BIBLES, WORLD } from "./bibles.ts";
import { TOPICS, keysFor, topicOf } from "./schema.ts";
import type { DialogueFile } from "./schema.ts";
import { validateDialogue } from "./validate.ts";
import type { Issue } from "./validate.ts";

const MODEL = "claude-opus-5-5";
const MAX_REPAIRS = 2;
const OUT_DIR = new URL("../../content/dialogue/", import.meta.url);

const SYSTEM = `${WORLD}

You are writing dialogue templates for a murder-mystery game. Cases are generated by code, so you never know the
facts of any particular case. Write reusable lines with {slots} that the game fills in. Rules:

- Use ONLY the slots listed for each key. Never write a room, time, weapon or character name directly; use a slot.
- {other}, {victim} and {witness} become the speaker's own way of referring to that person ("Folder",
  "dear Martin", "the steward"), so never put Mr/Mrs/Miss in front of them. Use {other.full} for a full name.
- Pronoun slots: {other.subject} (he/she), {other.object} (him/her), {other.possessive} (his/her), likewise for
  victim and witness. Verbs after them are singular: "{Other.subject} was".
- Capitalise a slot name to capitalise its value at the start of a sentence: {Other}, {Victim.subject}, {RoomName}.
- Each line is spoken aloud by one character, in their voice, as a complete reply. No stage directions, no quotes.
- Variants for the same key must differ in wording and attitude, not just punctuation.
- Never state facts the game supplies separately (where someone was, who they saw) except through the slots.`;

function prompt(speaker: CharId): string {
  const b = BIBLES[speaker];
  const views = Object.entries(b.views)
    .map(([id, v]) => `- ${CAST[id as CharId].name} (you call them "${v.address}"): ${v.view}`)
    .join("\n");
  const keys = keysFor(speaker)
    .map((key) => {
      const { topic, about } = topicOf(key);
      const spec = TOPICS[topic];
      const subject = about ? ` Here {other} is ${CAST[about].name}.` : "";
      const slots = spec.allowed.length ? spec.allowed.map((s) => `{${s}}`).join(" ") : "none";
      const required = spec.required.map((g) => `one of ${g.map((s) => `{${s}}`).join(" ")}`).join("; ");
      return `- "${key}": ${spec.variants} lines, each under ${spec.maxLength} characters. ${spec.brief}${subject} Slots: ${slots}.${required ? ` Must include ${required}.` : ""}`;
    })
    .join("\n");

  return `Write every dialogue template for ${CAST[speaker].name}.

<character>
${b.summary}
Voice: ${b.voice}
Habits: ${b.habits.join("; ")}.
Avoid: ${b.avoid.join("; ")}.
Sample lines: ${b.samples.map((s) => `"${s}"`).join(" ")}
How they see the others:
${views}
</character>

<keys>
${keys}
</keys>

Return a JSON object with exactly these keys, each an array of strings.`;
}

function schema(speaker: CharId) {
  const keys = keysFor(speaker);
  return {
    type: "object",
    properties: Object.fromEntries(keys.map((k) => [k, { type: "array", items: { type: "string" } }])),
    required: keys,
    additionalProperties: false,
  };
}

function describeIssues(issues: Issue[]): string {
  return issues.map((i) => `- [${i.key}] ${i.problem}${i.line ? `: "${i.line}"` : ""}`).join("\n");
}

async function generate(client: Anthropic, speaker: CharId): Promise<{ file: DialogueFile; issues: Issue[] }> {
  const messages: Anthropic.Beta.BetaMessageParam[] = [{ role: "user", content: prompt(speaker) }];
  let file: DialogueFile | null = null;
  let issues: Issue[] = [];

  for (let round = 0; round <= MAX_REPAIRS; round++) {
    const response = await client.beta.messages
      .stream({
        model: MODEL,
        max_tokens: 64000,
        betas: ["server-side-fallback-2026-07-01"],
        fallbacks: "default",
        output_config: { effort: "high", format: { type: "json_schema", schema: schema(speaker) } },
        system: SYSTEM,
        messages,
      })
      .finalMessage();

    if (response.stop_reason === "refusal") throw new Error(`${speaker}: request declined (${response.stop_details?.category ?? "no category"})`);
    if (response.stop_reason === "max_tokens") throw new Error(`${speaker}: output hit max_tokens`);
    const text = response.content.flatMap((b) => (b.type === "text" ? [b.text] : [])).join("");

    file = {
      character: speaker,
      source: { model: response.model, generatedAt: new Date().toISOString() },
      lines: JSON.parse(text) as Record<string, string[]>,
    };
    issues = validateDialogue(file);
    console.log(`  ${speaker} round ${round + 1}: ${issues.length} issue(s)`);
    if (issues.length === 0) break;

    // Append-only history: keep the full assistant turn, then ask for a corrected version.
    messages.push({ role: "assistant", content: response.content });
    messages.push({
      role: "user",
      content: `These lines failed validation:\n${describeIssues(issues)}\n\nReturn the complete JSON object again with every problem fixed. Keep all lines that passed.`,
    });
  }
  return { file: file!, issues };
}

async function main() {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const dryRun = args.includes("--dry-run");
  const speakers = args.filter((a) => !a.startsWith("--")) as CharId[];
  for (const s of speakers) if (!CHAR_IDS.includes(s)) throw new Error(`unknown character "${s}" (use: ${CHAR_IDS.join(", ")})`);
  if (speakers.length === 0) throw new Error(`name at least one character: ${CHAR_IDS.join(", ")}`);

  if (dryRun) {
    for (const s of speakers) console.log(`=== SYSTEM ===\n${SYSTEM}\n\n=== USER (${s}) ===\n${prompt(s)}\n`);
    return;
  }

  mkdirSync(OUT_DIR, { recursive: true });
  const client = new Anthropic();
  for (const speaker of speakers) {
    const target = new URL(`${speaker}.json`, OUT_DIR);
    if (existsSync(target) && !force) {
      console.log(`${speaker}: ${fileURLToPath(target)} exists; skipping (use --force to overwrite)`);
      continue;
    }
    console.log(`${speaker}: generating with ${MODEL}...`);
    const { file, issues } = await generate(client, speaker);
    // Files that still fail validation are kept as drafts for a human to fix.
    const out = issues.length === 0 ? target : new URL(`${speaker}.draft.json`, OUT_DIR);
    writeFileSync(out, `${JSON.stringify(file, null, 2)}\n`);
    console.log(`${speaker}: wrote ${fileURLToPath(out)}${issues.length ? `\n${describeIssues(issues)}` : ""}`);
  }
}

main().catch((err) => {
  if (err instanceof Anthropic.AuthenticationError) console.error("No valid credentials: set ANTHROPIC_API_KEY or run `ant auth login`.");
  else if (err instanceof Anthropic.RateLimitError) console.error("Rate limited; try again shortly.");
  else if (err instanceof Anthropic.APIError) console.error(`API error ${err.status}: ${err.message}`);
  else console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
